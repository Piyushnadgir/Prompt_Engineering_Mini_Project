"""AspectPulse design tokens: the single source of truth for colours, spacing and typography.

Pure Python (no Streamlit import) so the Plotly chart builders can share the palette.
`.streamlit/config.toml` mirrors the colour values for Streamlit's native widgets, and
`ui/styles.css` uses them through the CSS variables generated by `css_variables()`.
"""

from __future__ import annotations

COLORS = {
    "bg": "#090D16",
    "sidebar": "#060911",
    "surface": "#0F172A",
    "surface_2": "#131F37",
    "elevated": "#1E2A44",
    "text": "#F8FAFC",
    "text_2": "#94A3B8",
    "muted": "#64748B",
    "border": "#1E293B",
    "border_soft": "#162338",
    "accent": "#0EA5E9",
    "accent_hover": "#0284C7",
}

SENTIMENT = {
    "positive": "#34D399",
    "negative": "#F87171",
    "neutral": "#94A3B8",
    "mixed": "#FBBF24",
}

# Categorical series (prompt strategies, token types). Clean, distinguishable on dark surfaces.
SERIES = ["#0EA5E9", "#8B5CF6", "#34D399", "#FBBF24", "#F87171", "#38BDF8"]

SPACING = {"xs": "4px", "sm": "8px", "md": "12px", "lg": "16px", "xl": "24px", "2xl": "32px"}
RADII = {"sm": "5px", "md": "7px", "lg": "10px", "pill": "999px"}
FONT = {
    "family": "Inter, 'SF Pro Display', -apple-system, 'Segoe UI', system-ui, sans-serif",
    "mono": "'JetBrains Mono', 'Fira Code', Consolas, monospace",
    "xs": "11px",
    "sm": "12px",
    "base": "14px",
    "lg": "16px",
    "kpi": "28px",
}

TONES = {  # badge / callout tones: (foreground, translucent background)
    "accent": (COLORS["accent"], "rgba(14,165,233,0.14)"),
    "positive": (SENTIMENT["positive"], "rgba(52,211,153,0.14)"),
    "negative": (SENTIMENT["negative"], "rgba(248,113,113,0.14)"),
    "neutral": (SENTIMENT["neutral"], "rgba(148,163,184,0.14)"),
    "mixed": (SENTIMENT["mixed"], "rgba(251,191,36,0.14)"),
    "warning": (SENTIMENT["mixed"], "rgba(251,191,36,0.12)"),
}


def css_variables() -> str:
    """`:root` block exposing the tokens to ui/styles.css."""
    lines = [f"--riq-{k.replace('_', '-')}: {v};" for k, v in COLORS.items()]
    lines += [f"--riq-{k}: {v};" for k, v in SENTIMENT.items()]
    lines += [f"--riq-space-{k}: {v};" for k, v in SPACING.items()]
    lines += [f"--riq-radius-{k}: {v};" for k, v in RADII.items()]
    lines += [f"--riq-font: {FONT['family']};", f"--riq-mono: {FONT['mono']};"]
    for name, (fg, bg) in TONES.items():
        lines += [f"--riq-{name}-fg: {fg};", f"--riq-{name}-bg: {bg};"]
    return ":root {" + "".join(lines) + "}"
